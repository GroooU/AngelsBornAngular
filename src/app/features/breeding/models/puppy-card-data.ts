/**
 * Данные для карточки щенка в разделе «Наше разведение».
 */
export interface PuppyCardData {
  /** Заголовок карточки, например: "Мальчик 1 - Angel's Born Sarmat (Сармат)" */
  title: string;
  /** Пути к фотографиям */
  photoUrls: string[];
  /** Текст для атрибута alt у изображений */
  altText: string;
  /** Информация о владельце, например: "Владелец: Лобковская Полина, г. Екатеринбург" */
  ownerInfo: string;
}
